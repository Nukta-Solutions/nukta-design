import { palette, resolvePaletteRef, type PaletteHue } from "./palette";
import {
  duration,
  easing,
  fontFamily,
  fontSize,
  fontWeight,
  lineHeight,
  radius,
  shadow,
  spacing,
  spacingSteps,
  zIndex,
} from "./scales";
import { semanticColorNames, semanticColors, type ColorMode } from "./semantic";

const PREFIX = "nukta";

function block(selector: string, lines: string[], indent = ""): string {
  return `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join("\n")}\n${indent}}`;
}

function paletteVars(): string[] {
  return (Object.keys(palette) as PaletteHue[]).flatMap((hue) =>
    Object.entries(palette[hue]).map(([step, value]) =>
      step === "DEFAULT"
        ? `--${PREFIX}-palette-${hue}: ${value};`
        : `--${PREFIX}-palette-${hue}-${step}: ${value};`,
    ),
  );
}

function paletteVarName(ref: string): string {
  const [hue, step] = ref.split(".");
  return step === "DEFAULT" ? `--${PREFIX}-palette-${hue}` : `--${PREFIX}-palette-${hue}-${step}`;
}

function modeVars(mode: ColorMode): string[] {
  return semanticColorNames.map(
    (name) => `--${PREFIX}-${name}: var(${paletteVarName(semanticColors[mode][name])});`,
  );
}

/**
 * Generates the Tailwind v4 theme stylesheet:
 *  - palette + semantic CSS variables for light and dark mode
 *  - dark mode via `.dark` class OR `prefers-color-scheme: dark` (opt out with `.light`)
 *  - a `@theme inline` block that maps tokens to Tailwind utilities and removes Tailwind's
 *    default palette, so only semantic colors exist (`bg-primary`, not `bg-blue-500`).
 */
export function buildThemeCss(): string {
  const header = `/*\n * @nukta-solutions/tokens — generated by scripts/build.ts. Do not edit by hand.\n */`;

  const root = block(":root", [
    "color-scheme: light;",
    ...paletteVars(),
    ...modeVars("light"),
    ...Object.entries(zIndex).map(([k, v]) => `--z-${k}: ${v};`),
    ...Object.entries(duration).map(([k, v]) => `--duration-${k}: ${v};`),
  ]);

  const darkClass = block(".dark", ["color-scheme: dark;", ...modeVars("dark")]);
  const darkMedia = `@media (prefers-color-scheme: dark) {\n${block(
    ":root:not(.light)",
    ["color-scheme: dark;", ...modeVars("dark")],
    "  ",
  )}\n}`;

  const variant = [
    "/* `dark:` matches the .dark class, or the OS preference unless .light is set. */",
    "@custom-variant dark {",
    "  &:where(.dark, .dark *) {",
    "    @slot;",
    "  }",
    "  @media (prefers-color-scheme: dark) {",
    "    &:where(:root:not(.light), :root:not(.light) *) {",
    "      @slot;",
    "    }",
    "  }",
    "}",
  ].join("\n");

  const theme = block("@theme inline", [
    "--color-*: initial;",
    ...semanticColorNames.map((n) => `--color-${n}: var(--${PREFIX}-${n});`),
    "",
    `--spacing: ${spacing};`,
    "",
    "--radius-*: initial;",
    ...Object.entries(radius).map(([k, v]) => `--radius-${k}: ${v};`),
    "",
    "--font-*: initial;",
    ...Object.entries(fontFamily).map(([k, v]) => `--font-${k}: ${v};`),
    "",
    "--text-*: initial;",
    ...Object.entries(fontSize).flatMap(([k, v]) => [
      `--text-${k}: ${v.size};`,
      `--text-${k}--line-height: ${v.lineHeight};`,
    ]),
    "",
    "--font-weight-*: initial;",
    ...Object.entries(fontWeight).map(([k, v]) => `--font-weight-${k}: ${v};`),
    "",
    "--leading-*: initial;",
    ...Object.entries(lineHeight).map(([k, v]) => `--leading-${k}: ${v};`),
    "",
    "--shadow-*: initial;",
    ...Object.entries(shadow).map(([k, v]) => `--shadow-${k}: ${v};`),
    "",
    "--ease-*: initial;",
    ...Object.entries(easing).map(([k, v]) => `--ease-${k}: ${v};`),
  ]).replace(/^ {2}$/gm, "");

  return [header, variant, theme, root, darkClass, darkMedia].join("\n\n") + "\n";
}

/** Flat, resolved token JSON (W3C design-tokens style) for Figma sync and other tooling. */
export function buildTokensJson() {
  const color = (mode: ColorMode) =>
    Object.fromEntries(
      semanticColorNames.map((n) => [
        n,
        {
          $type: "color",
          $value: resolvePaletteRef(semanticColors[mode][n]),
          $description: `palette: ${semanticColors[mode][n]}`,
        },
      ]),
    );
  const dims = (o: Record<string, string>) =>
    Object.fromEntries(Object.entries(o).map(([k, v]) => [k, { $type: "dimension", $value: v }]));

  return {
    $schema: "https://design-tokens.github.io/community-group/format/",
    color: { light: color("light"), dark: color("dark") },
    palette: Object.fromEntries(
      Object.entries(palette).map(([hue, steps]) => [
        hue,
        Object.fromEntries(
          Object.entries(steps).map(([s, v]) => [s, { $type: "color", $value: v }]),
        ),
      ]),
    ),
    spacing: Object.fromEntries(
      spacingSteps.map((s) => [
        String(s),
        { $type: "dimension", $value: `calc(${spacing} * ${s})` },
      ]),
    ),
    radius: dims(radius),
    fontFamily: Object.fromEntries(
      Object.entries(fontFamily).map(([k, v]) => [k, { $type: "fontFamily", $value: v }]),
    ),
    fontSize: Object.fromEntries(
      Object.entries(fontSize).map(([k, v]) => [
        k,
        { $type: "dimension", $value: v.size, lineHeight: v.lineHeight },
      ]),
    ),
    fontWeight: Object.fromEntries(
      Object.entries(fontWeight).map(([k, v]) => [k, { $type: "fontWeight", $value: Number(v) }]),
    ),
    lineHeight: Object.fromEntries(
      Object.entries(lineHeight).map(([k, v]) => [k, { $type: "number", $value: Number(v) }]),
    ),
    shadow: Object.fromEntries(
      Object.entries(shadow).map(([k, v]) => [k, { $type: "shadow", $value: v }]),
    ),
    zIndex: Object.fromEntries(
      Object.entries(zIndex).map(([k, v]) => [k, { $type: "number", $value: Number(v) }]),
    ),
    duration: Object.fromEntries(
      Object.entries(duration).map(([k, v]) => [k, { $type: "duration", $value: v }]),
    ),
    easing: Object.fromEntries(
      Object.entries(easing).map(([k, v]) => [k, { $type: "cubicBezier", $value: v }]),
    ),
  };
}
